// 2. Pixel checks on the rendered page.
// ---------------------------------------------------------------------------
function hiDominant(img, x0, y0, x1, y1, maxSamples, collect) {
  const W = img.width, H = img.height, d = img.data;
  x0 = Math.max(0, Math.floor(x0)); y0 = Math.max(0, Math.floor(y0));
  x1 = Math.min(W, Math.ceil(x1)); y1 = Math.min(H, Math.ceil(y1));
  const w = x1 - x0, h = y1 - y0;
  if (w <= 0 || h <= 0) return null;
  const step = Math.max(1, Math.floor(Math.sqrt((w * h) / maxSamples)));
  const hist = new Map();
  for (let yy = y0; yy < y1; yy += step) {
    for (let xx = x0; xx < x1; xx += step) {
      const k = (yy * W + xx) * 4;
      const r = d[k], g = d[k + 1], b = d[k + 2];
      if (collect) collect.push([r, g, b]);
      const key = (r >> 4) << 8 | (g >> 4) << 4 | (b >> 4);
      const e = hist.get(key);
      if (e) { e.n++; e.r += r; e.g += g; e.b += b; } else hist.set(key, { n: 1, r, g, b });
    }
  }
  let best = null;
  for (const e of hist.values()) if (!best || e.n > best.n) best = e;
  return { rgb: [best.r / best.n, best.g / best.n, best.b / best.n], areaPx: w * h };
}

// Compare the page rendered normally (A) with the same page rendered without
// any text (B). Pixels where A moved away from B toward the text colour are the
// text's visible ink. B also gives the true background behind the text.
function hiPixelStats(imgA, imgB, rect, textRgb) {
  const W = imgA.width, H = imgA.height, a = imgA.data, b = imgB.data;
  const x0 = Math.max(0, Math.floor(rect[0])), y0 = Math.max(0, Math.floor(rect[1]));
  const x1 = Math.min(W, Math.ceil(rect[2])), y1 = Math.min(H, Math.ceil(rect[3]));
  const w = x1 - x0, h = y1 - y0;
  if (w <= 0 || h <= 0) return null;
  const bgDom = hiDominant(imgB, x0, y0, x1, y1, 3000);
  const step = Math.max(1, Math.floor(Math.sqrt((w * h) / 6000)));
  let n = 0, ink = 0;
  for (let yy = y0; yy < y1; yy += step) {
    for (let xx = x0; xx < x1; xx += step) {
      const k = (yy * W + xx) * 4;
      const pa = [a[k], a[k + 1], a[k + 2]], pb = [b[k], b[k + 1], b[k + 2]];
      n++;
      // Colour unknown (pattern, shading): any visible change counts as ink.
      if (hiDist(pa, pb) > 24 && (!textRgb || hiDist(pa, textRgb) + 8 < hiDist(pb, textRgb))) ink++;
    }
  }
  return { bg: bgDom.rgb, inkFrac: ink / n, areaPx: w * h };
}

function hiInkShare(img, rect, bg) {
  const W = img.width, H = img.height, d = img.data;
  const x0 = Math.max(0, Math.floor(rect[0])), y0 = Math.max(0, Math.floor(rect[1]));
  const x1 = Math.min(W, Math.ceil(rect[2])), y1 = Math.min(H, Math.ceil(rect[3]));
  if (x1 <= x0 || y1 <= y0) return 0;
  let n = 0, ink = 0;
  for (let yy = y0; yy < y1; yy++) {
    for (let xx = x0; xx < x1; xx++) {
      const k = (yy * W + xx) * 4;
      n++;
      if (hiDist([d[k], d[k + 1], d[k + 2]], bg) > 40) ink++;
    }
  }
  return ink / n;
}

function hiMarkShare(img, rect) {
  const W = img.width, H = img.height, d = img.data;
  const x0 = Math.max(0, Math.floor(rect[0])), y0 = Math.max(0, Math.floor(rect[1]));
  const x1 = Math.min(W, Math.ceil(rect[2])), y1 = Math.min(H, Math.ceil(rect[3]));
  if (x1 <= x0 || y1 <= y0) return 0;
  const bg = hiDominant(img, x0, y0, x1, y1, 3000).rgb;
  const step = Math.max(1, Math.floor(Math.sqrt(((x1 - x0) * (y1 - y0)) / 6000)));
  let n = 0, marks = 0;
  for (let yy = y0; yy < y1; yy += step) {
    for (let xx = x0; xx < x1; xx += step) {
      const k = (yy * W + xx) * 4;
      n++;
      if (hiDist([d[k], d[k + 1], d[k + 2]], bg) > 60) marks++;
    }
  }
  return marks / n;
}

