const HI_ZW_STRICT = /[\u200B\u2060-\u2064\uFEFF\u180E]/g;   // no legitimate visible role
const HI_ZW_JOIN = /[\u200C-\u200F]/g;                        // joiners and marks: normal in some scripts and emoji
const HI_ZW_ANY_RUN = /[\u200B-\u200F\u2060-\u2064\uFEFF\u180E]{8,}/g; // long contiguous runs: encoded data
const HI_BIDI = /[\u202A-\u202E\u2066-\u2069]/g;
const HI_TAG = /[\u{E0000}-\u{E007F}]+/gu;
const HI_VS_RUN = /[\uFE00-\uFE0F\u{E0100}-\u{E01EF}]{4,}/gu;
const HI_INVISIBLE_ALL = /[\u200B-\u200F\u2060-\u2064\uFEFF\u180E\u202A-\u202E\u2066-\u2069\uFE00-\uFE0F\u{E0000}-\u{E007F}\u{E0100}-\u{E01EF}]/gu;

function hiDecodeTags(s) {
  let out = "";
  for (const ch of s) { const cp = ch.codePointAt(0) - 0xE0000; if (cp >= 0x20 && cp < 0x7F) out += String.fromCharCode(cp); }
  return out;
}
// "Emoji smuggling": one byte per variation selector (VS1-16 = 0-15, VS17-256 = 16-255).
function hiDecodeVariation(s) {
  const bytes = [];
  for (const ch of s) {
    const cp = ch.codePointAt(0);
    if (cp >= 0xFE00 && cp <= 0xFE0F) bytes.push(cp - 0xFE00);
    else if (cp >= 0xE0100 && cp <= 0xE01EF) bytes.push(cp - 0xE0100 + 16);
  }
  let out = "";
  try { out = new TextDecoder("utf-8").decode(new Uint8Array(bytes)); } catch (_) { return ""; }
  const printable = (out.match(/[\p{L}\p{N}\p{P}\p{Zs}]/gu) || []).length;
  return out.length && printable / out.length > 0.85 && hiReadable(out) ? out : "";
}
function hiCodepoints(chars) {
  const seen = new Set();
  for (const ch of chars) seen.add("U+" + ch.codePointAt(0).toString(16).toUpperCase().padStart(4, "0"));
  return [...seen].slice(0, 6).join(", ");
}
function hiVisibleContext(s) { return s.replace(HI_INVISIBLE_ALL, "").replace(/\s+/g, " ").trim().slice(0, 60); }

// Collects invisible-character evidence across the whole document, then
// emits one finding per kind (instead of one per page).
function hiUnicodeCollector() {
  const acc = { strict: [], join: [], bidi: [], runs: 0, pagesZw: new Set(), pagesBidi: new Set(), ctxZw: "", ctxBidi: "", out: [] };
  const where = (loc) => loc;
  return {
    scan(text, loc, pageNo) {
      for (const m of text.matchAll(HI_TAG)) {
        const decoded = hiDecodeTags(m[0]);
        acc.out.push({ type: "unicode-tags", severity: "high", text: decoded || `(${[...m[0]].length})`,
          detail: { k: "tagChars", p: { n: [...m[0]].length, ctx: hiVisibleContext(text) } }, where: where(loc), page: pageNo,
          patterns: hiMatchPatterns(decoded) });
      }
      for (const m of text.matchAll(HI_VS_RUN)) {
        const decoded = hiDecodeVariation(m[0]);
        acc.out.push({ type: "variation-run", severity: "medium",
          text: decoded || `${[...m[0]].length} × ${hiCodepoints([...m[0]])}`,
          detail: { k: decoded ? "vsDecoded" : "context", p: { n: [...m[0]].length, ctx: hiVisibleContext(text) } },
          where: where(loc), page: pageNo, patterns: decoded ? hiMatchPatterns(decoded) : [] });
      }
      const strict = text.match(HI_ZW_STRICT) || [], join = text.match(HI_ZW_JOIN) || [];
      const runs = (text.match(HI_ZW_ANY_RUN) || []).length;
      if (strict.length || runs) {
        acc.strict.push(...strict); acc.join.push(...join); acc.runs += runs;
        if (pageNo) acc.pagesZw.add(pageNo);
        if (!acc.ctxZw) acc.ctxZw = hiVisibleContext(text);
      }
      const bd = text.match(HI_BIDI) || [];
      if (bd.length) { acc.bidi.push(...bd); if (pageNo) acc.pagesBidi.add(pageNo); if (!acc.ctxBidi) acc.ctxBidi = hiVisibleContext(text); }
    },
    finish() {
      const out = acc.out.slice();
      const pagesList = (set) => [...set].slice(0, 8).join(", ") + (set.size > 8 ? "…" : "");
      const zwTotal = acc.strict.length + (acc.runs ? acc.join.length : 0);
      if (acc.runs || acc.strict.length >= 3) {
        out.push({ type: "zero-width", severity: acc.runs ? "medium" : "low",
          text: `${zwTotal} × ${hiCodepoints([...acc.strict, ...(acc.runs ? acc.join : [])])}`,
          detail: { k: acc.pagesZw.size ? "zwPages" : "context", p: { pages: pagesList(acc.pagesZw), ctx: acc.ctxZw } },
          page: acc.pagesZw.size === 1 ? [...acc.pagesZw][0] : null, patterns: [] });
      }
      if (acc.bidi.length) {
        out.push({ type: "bidi", severity: "low", text: `${acc.bidi.length} × ${hiCodepoints(acc.bidi)}`,
          detail: { k: acc.pagesBidi.size ? "zwPages" : "context", p: { pages: pagesList(acc.pagesBidi), ctx: acc.ctxBidi } },
          page: acc.pagesBidi.size === 1 ? [...acc.pagesBidi][0] : null, patterns: [] });
      }
      return out;
    },
  };
}

// Downscale the rendered page into a compressed image for the on-screen preview.
// Resolves to { url, blob }. A blob: URL keeps memory low; the blob itself is
// kept so the page can fall back to a data: URL where blob: images are blocked
// (some browser engines in sandboxed frames, e.g. in-app file viewers on phones).
function hiPreview(src, maxW) {
  const k = Math.min(1, maxW / src.width);
  const c = document.createElement("canvas");
  c.width = Math.max(1, Math.round(src.width * k));
  c.height = Math.max(1, Math.round(src.height * k));
  const g = c.getContext("2d");
  g.imageSmoothingQuality = "high";
  g.drawImage(src, 0, 0, c.width, c.height);
  return new Promise((res) => {
    const done = (b) => {
      let url = null;
      if (b) { try { url = URL.createObjectURL(b); } catch (_) { url = null; } }
      if (!url) { try { url = c.toDataURL("image/jpeg", 0.88); } catch (_) { url = ""; } }
      c.width = c.height = 0;
      res({ url, blob: b || null });
    };
    try { c.toBlob(done, "image/jpeg", 0.88); } catch (_) { done(null); }
  });
}

// ---------------------------------------------------------------------------
// 4. Raw safety net: read the file bytes directly.
// pdf.js only shows what a viewer needs. Text can also sit where no page ever
// draws it but other extractors still read it: /ActualText and /Alt entries,
// objects nothing points to, old revisions, bytes after %%EOF. This pass inflates
// every stream with the browser's own DecompressionStream and looks for AI
// instructions anywhere. It only reports instruction phrases (high), and only
// ones not already explained by a page or another finding.
// ---------------------------------------------------------------------------
const HI_RAW = { maxStreamOut: 20 << 20, maxTotalOut: 120 << 20, maxHits: 12, chunk: 4000 };

async function hiInflate(u8) {
  if (typeof DecompressionStream !== "function" || !u8 || !u8.length) return null;
  for (const fmt of ["deflate", "deflate-raw"]) {
    const chunks = []; let total = 0;
    try {
      const ds = new DecompressionStream(fmt);
      const writer = ds.writable.getWriter();
      writer.write(u8).catch(() => {}); writer.close().catch(() => {});
      const reader = ds.readable.getReader();
      try {
        for (;;) {
          const { done, value } = await reader.read();
          if (done) break;
          chunks.push(value); total += value.length;
          if (total > HI_RAW.maxStreamOut) { reader.cancel().catch(() => {}); break; }
        }
      } catch (_) { /* truncated or trailing bytes: keep what came out */ }
    } catch (_) { /* format not supported */ }
    if (total) {
      const out = new Uint8Array(total); let o = 0;
      for (const c of chunks) { out.set(c, o); o += c.length; }
      return out;
    }
  }
  return null;
}

function hiPdfTextString(bytes) {
  if (bytes.length >= 2 && bytes[0] === 0xFE && bytes[1] === 0xFF) return new TextDecoder("utf-16be").decode(bytes.subarray(2));
  if (bytes.length >= 3 && bytes[0] === 0xEF && bytes[1] === 0xBB && bytes[2] === 0xBF) return new TextDecoder("utf-8").decode(bytes.subarray(3));
  return new TextDecoder("windows-1252").decode(bytes);
}

// Pull every string literal "(...)" and hex string "<...>" out of PDF syntax.
// Strings inside one [ ] array (a TJ show-text array) are joined without spaces.
function hiPdfStrings(s, limit = 200000) {
  const items = [];
  const n = s.length;
  let arr = 0;
  for (let i = 0; i < n && items.length < limit; i++) {
    const c = s.charCodeAt(i);
    if (c === 0x5B) { arr++; continue; }                 // [
    if (c === 0x5D) { if (arr) arr--; continue; }        // ]
    if (c === 0x28) {                                    // (
      const bytes = []; let depth = 1, j = i + 1;
      for (; j < n && depth; j++) {
        let ch = s.charCodeAt(j);
        if (ch === 0x5C) {                               // backslash escape
          const e = s[++j];
          if (e === "n") bytes.push(10); else if (e === "r") bytes.push(13); else if (e === "t") bytes.push(9);
          else if (e === "b") bytes.push(8); else if (e === "f") bytes.push(12);
          else if (e === "\r") { if (s[j + 1] === "\n") j++; }
          else if (e === "\n") { /* line continuation */ }
          else if (e >= "0" && e <= "7") {
            let oct = e; while (oct.length < 3 && s[j + 1] >= "0" && s[j + 1] <= "7") oct += s[++j];
            bytes.push(parseInt(oct, 8) & 255);
          } else if (e !== undefined) bytes.push(e.charCodeAt(0) & 255);
          continue;
        }
        if (ch === 0x28) depth++;
        else if (ch === 0x29 && --depth === 0) break;
        bytes.push(ch & 255);
      }
      items.push({ start: i, text: hiPdfTextString(new Uint8Array(bytes)), inArray: arr > 0 });
      i = j;
      continue;
    }
    if (c === 0x3C && s.charCodeAt(i + 1) !== 0x3C) {    // < but not <<
      const j = s.indexOf(">", i + 1);
      if (j < 0 || j - i > 200000) continue;
      const hex = s.slice(i + 1, j).replace(/\s+/g, "");
      if (!/^[0-9A-Fa-f]*$/.test(hex) || hex.length < 4) { i = j; continue; }
      const h = hex.length % 2 ? hex + "0" : hex;
      const bytes = new Uint8Array(h.length / 2);
      for (let k = 0; k < bytes.length; k++) bytes[k] = parseInt(h.substr(k * 2, 2), 16);
      items.push({ start: i, text: hiPdfTextString(bytes), inArray: arr > 0 });
      i = j;
      continue;
    }
    if (c === 0x3C) i++; // skip the second < of <<
  }
  // Name of the key right before each string, e.g. /ActualText (...)
  for (const it of items) {
    const before = s.slice(Math.max(0, it.start - 48), it.start);
    const m = before.match(/\/([A-Za-z0-9_.#:-]+)\s*$/);
    it.key = m ? m[1] : null;
  }
  return items;
}

// Join extracted strings into searchable chunks. Keys like /ActualText or /Alt
// keep their own chunk so the finding can say where it came from.
function hiRawChunks(items) {
  const out = [];
  let buf = "", prevArr = false;
  const flush = () => { if (buf.trim()) out.push({ text: buf, key: null }); buf = ""; };
  for (const it of items) {
    if (it.key && !it.inArray && it.text.length >= 8 && !/^(Tj|TJ|F\d+)$/.test(it.key)) { out.push({ text: it.text, key: it.key }); continue; }
    buf += (it.inArray && prevArr ? "" : " ") + it.text;
    prevArr = it.inArray;
    if (buf.length > HI_RAW.chunk) flush();
  }
  flush();
  return out;
}

const hiKey = (s) => hiNormalize(s).toLowerCase().replace(/[^\p{L}\p{N}]+/gu, "");

async function hiRawScan(bytes, haystack) {
  const hits = [];
  if (!bytes || !bytes.length) return hits;
  const hay = hiKey(haystack);
  const seen = new Set();
  // Already explained if its words show up, in order and close together, in
  // the visible text or in another finding (spacing and splitting may differ).
  const inOrder = (words) => {
    for (let from = hay.indexOf(words[0]); from >= 0; from = hay.indexOf(words[0], from + 1)) {
      let pos = from + words[0].length, ok = true;
      for (const w of words.slice(1)) {
        const i = hay.indexOf(w, pos);
        if (i < 0 || i - pos > 60) { ok = false; break; }
        pos = i + w.length;
      }
      if (ok) return true;
    }
    return false;
  };
  const known = (m) => {
    const k = hiKey(m);
    if (!k || seen.has(k)) return true;
    seen.add(k);
    const words = hiNormalize(m).toLowerCase().match(/[\p{L}\p{N}]{2,}/gu) || [];
    return hay.includes(k) || (words.length > 0 && inOrder(words));
  };
  const check = (text, detail) => {
    if (hits.length >= HI_RAW.maxHits || !hiReadable(text)) return;
    const pats = hiMatchPatterns(text);
    const fresh = pats.filter((m) => !known(m.replace(/^base64: /, "")));
    if (!fresh.length) return;
    const k = hiNormalize(text).indexOf(fresh[0]);
    const ctx = k < 0 ? text : hiNormalize(text).slice(Math.max(0, k - 120), k + fresh[0].length + 200);
    hits.push({ type: "raw-text", severity: "high", page: null, patterns: fresh, text: hiClip(ctx.replace(/\s+/g, " ")), detail });
  };

  const s = new TextDecoder("windows-1252").decode(bytes);   // one char per byte
  const body = [];
  let last = 0, totalOut = 0;
  const streamRe = /stream(\r\n|\n|\r)/g;
  let m;
  while ((m = streamRe.exec(s)) && hits.length < HI_RAW.maxHits) {
    if (s.slice(m.index - 3, m.index) === "end") continue;
    const start = m.index + m[0].length;
    const objAt = s.lastIndexOf("obj", m.index);
    const dict = objAt >= 0 && m.index - objAt < 8192 ? s.slice(objAt, m.index) : s.slice(Math.max(0, m.index - 2048), m.index);
    const objNo = (s.slice(Math.max(0, objAt - 24), objAt).match(/(\d+)\s+\d+\s+$/) || [])[1] || "?";
    const len = dict.match(/\/Length\s+(\d+)(?!\s+\d+\s+R)/);
    let end = len ? start + parseInt(len[1], 10) : -1;
    if (end < start || end > s.length || !/^\s*endstream/.test(s.slice(end, end + 32))) end = s.indexOf("endstream", start);
    if (end < 0) break;
    body.push(s.slice(last, m.index));
    last = end;
    streamRe.lastIndex = end;
    // Images, fonts, cross-reference data and embedded files (scanned on their own) are skipped.
    if (/\/Subtype\s*\/(Image|Type1C|CIDFontType0C|OpenType)\b|\/Length[123]\b|\/Type\s*\/(XRef|EmbeddedFile)\b|\/Predictor\b/.test(dict)) continue;
    const filters = (dict.match(/\/Filter\s*(\[[^\]]*\]|\/[A-Za-z0-9]+)/) || [])[1] || "";
    const names = filters.match(/\/[A-Za-z0-9]+/g) || [];
    let data = bytes.subarray(start, end);
    if (names.length === 1 && /^\/(FlateDecode|Fl)$/.test(names[0])) {
      if (totalOut > HI_RAW.maxTotalOut) continue;
      data = await hiInflate(data);
      if (!data) continue;
      totalOut += data.length;
    } else if (names.length) continue;
    const text = new TextDecoder("windows-1252").decode(data);
    for (const ch of hiRawChunks(hiPdfStrings(text))) {
      check(ch.text, ch.key ? { k: "rawKey", p: { f: "/" + ch.key, obj: objNo } } : { k: "rawStream", p: { obj: objNo } });
    }
    // Plain-text streams (XMP, JavaScript, XFA) are also searched as they are.
    if (!/\b(BT|Tj|TJ)\b/.test(text.slice(0, 4000))) {
      for (let i = 0; i < text.length && i < 2000000; i += HI_RAW.chunk) check(text.slice(i, i + HI_RAW.chunk + 200), { k: "rawStream", p: { obj: objNo } });
    }
  }
  body.push(s.slice(last));
  const outside = body.join("\n");
  const eof = outside.lastIndexOf("%%EOF");
  const main = eof >= 0 ? outside.slice(0, eof) : outside;
  const tail = eof >= 0 ? outside.slice(eof + 5) : "";
  for (const ch of hiRawChunks(hiPdfStrings(main))) check(ch.text, ch.key ? { k: "rawKey", p: { f: "/" + ch.key, obj: "?" } } : { k: "rawBody", p: {} });
  for (let i = 0; i < main.length && i < 4000000; i += HI_RAW.chunk) check(main.slice(i, i + HI_RAW.chunk + 200), { k: "rawBody", p: {} });
  if (tail.trim()) check(tail.slice(0, 200000), { k: "rawEof", p: {} });
  return hits;
}

// Document outline (bookmarks): titles every reader keeps out of the page.
async function hiOutlineTitles(doc) {
  const out = [];
  let ol = null;
  try { ol = await doc.getOutline(); } catch (_) { return out; }
  const walk = (items, depth) => {
    for (const it of items || []) {
      if (out.length > 5000 || depth > 20) return;
      if (it && typeof it.title === "string") out.push(it.title);
      walk(it && it.items, depth + 1);
    }
  };
  walk(ol, 0);
  return out;
}

// ---------------------------------------------------------------------------
// 5. Main entry point.
// ---------------------------------------------------------------------------
async function hiAnalyze(pdfjsLib, data, opts = {}) {
  const onProgress = opts.onProgress || (() => {});
  const scale = opts.renderScale || HI_RULES.renderScale;
  const depth = opts.depth || 0;
  // pdf.js may hand the buffer to its worker; keep our own copy for the raw pass.
  const rawBytes = data instanceof Uint8Array ? data.slice() : new Uint8Array(data).slice();
  const task = pdfjsLib.getDocument({
    data, isEvalSupported: false, useSystemFonts: true, verbosity: 0,
    stopAtErrors: false, enableXfa: false,
  });
  const doc = await task.promise;
  let ocConfig = null;
  try { ocConfig = await doc.getOptionalContentConfig(); } catch (_) { /* none */ }

  const OPS = pdfjsLib.OPS;
  // One analysis canvas, reused for every page. Previews are kept as small
  // compressed images so a 200-page PDF doesn't hold gigabytes of pixels.
  const canvas = document.createElement("canvas");
  const ctx = canvas.getContext("2d", { willReadFrequently: true });
  const previewMaxW = opts.previewWidth || 900;
  const uni = hiUnicodeCollector();
  const report = { numPages: doc.numPages, pages: [], findings: [], cleanTextPages: [] };
  const DISABLE = pdfjsLib.AnnotationMode ? pdfjsLib.AnnotationMode.DISABLE : 0;

  for (let p = 1; p <= doc.numPages; p++) {
    onProgress(p, doc.numPages);
    const page = await doc.getPage(p);
    const viewport = page.getViewport({ scale });
    const tA = performance.now();
    const opList = await page.getOperatorList({ annotationMode: DISABLE });
    const tB = performance.now();
    const { runs, images } = hiTraceRuns(OPS, opList, page, ocConfig);

    canvas.width = Math.ceil(viewport.width);
    canvas.height = Math.ceil(viewport.height);
    ctx.fillStyle = "#ffffff";
    ctx.fillRect(0, 0, canvas.width, canvas.height);
    await page.render({ canvas, canvasContext: ctx, viewport, annotationMode: DISABLE }).promise;
    const img = ctx.getImageData(0, 0, canvas.width, canvas.height);
    // Same page without any text. The renderer optimises its own copy of the
    // operator list, so ops are matched by type, not by index.
    const textOps = new Set([OPS.showText, OPS.showSpacedText, OPS.nextLineShowText, OPS.nextLineSetSpacingShowText]);
    ctx.fillStyle = "#ffffff";
    ctx.fillRect(0, 0, canvas.width, canvas.height);
    await page.render({
      canvas, canvasContext: ctx, viewport, annotationMode: DISABLE,
      operationsFilter: (i, list) => !(list && textOps.has(list.fnArray[i])),
    }).promise;
    const imgNoText = ctx.getImageData(0, 0, canvas.width, canvas.height);
    ctx.putImageData(img, 0, 0); // restore the normal render for the preview
    const tC = performance.now();

    const [vx0, vy0, vx1, vy1] = page.view;
    const pageArea = (vx1 - vx0) * (vy1 - vy0);
    const imgArea = images.reduce((s, b) => s + Math.max(0, Math.min(b[2], vx1) - Math.max(b[0], vx0)) * Math.max(0, Math.min(b[3], vy1) - Math.max(b[1], vy0)), 0);
    // A scanned page: mostly picture, and nearly all of its text is the invisible
    // searchable layer. A designed page with a background picture and ordinary
    // visible text is not a scanned page, so invisible text on it stays suspicious.
    const textChars = (want) => runs.reduce((n, r) => n + ((r.renderMode === 3 || r.renderMode === 7) === want ? r.text.replace(/\s/g, "").length : 0), 0);
    const visibleChars = textChars(false), invisibleChars = textChars(true);
    const looksScanned = imgArea / pageArea > 0.5 && visibleChars <= 0.2 * Math.max(1, visibleChars + invisibleChars);

    const toPx = (bb) => {
      const vt = viewport.transform;
      const pts = [[bb[0], bb[1]], [bb[2], bb[1]], [bb[0], bb[3]], [bb[2], bb[3]]].map((q) => hiApply(q, vt));
      const xs = pts.map((q) => q[0]), ys = pts.map((q) => q[1]);
      return [Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)];
    };

    const pageFindings = [];
    const visibleRuns = [];
    const noInkChecks = [];
    for (const run of hiGroupRuns(runs)) {
      if (!run.text || !run.text.replace(/\s/g, "").length) continue;
      const [bx0, by0, bx1, by1] = run.bbox;
      let type = null, detail = null, noInkRect = null;
      if (run.renderMode === 3 || run.renderMode === 7) {
        type = looksScanned ? "ocr-layer" : "invisible-mode";
        detail = { k: "renderMode", p: { mode: run.renderMode } };
      } else if (run.ocHidden) {
        type = "hidden-layer";
      } else if (run.alpha < HI_RULES.minAlpha) {
        type = "transparent"; detail = { k: "opacity", p: { pct: Math.round(run.alpha * 100) } };
      } else if (bx1 < vx0 - 1 || bx0 > vx1 + 1 || by1 < vy0 - 1 || by0 > vy1 + 1) {
        type = "off-page"; detail = { k: "position", p: { x: Math.round(run.base[0]), y: Math.round(run.base[1]), w: Math.round(vx1 - vx0), h: Math.round(vy1 - vy0) } };
      } else if (hiOutsideShare(run.bbox, page.view) >= HI_RULES.partialOffShare &&
                 (bx1 - bx0) * hiOutsideShare(run.bbox, page.view) >= 3 * Math.max(run.effSize, 1)) {
        // Starts on the page, but a large part runs past the edge where nobody can see it.
        type = "partial-off-page"; detail = { k: "partialOff", p: { pct: Math.round(hiOutsideShare(run.bbox, page.view) * 100) } };
      } else if (run.effSize < HI_RULES.tinyFontPt) {
        type = "tiny"; detail = { k: "size", p: { pt: run.effSize.toFixed(2) } };
      } else if (run.hscale < HI_RULES.squeezeScale) {
        type = "tiny"; detail = { k: "hscale", p: { pct: Math.round(run.hscale * 100) } };
      } else {
        const rgb = hiHexToRgb(run.color);
        const rect = toPx(run.bbox);
        const st = hiPixelStats(img, imgNoText, rect, rgb);
        if (st && !rgb) {
          // Fill is a pattern, shading or other colour we can't read: judge by ink alone.
          if (st.inkFrac < HI_RULES.coveredInkFrac && st.areaPx >= HI_RULES.minCoveredAreaPx) {
            type = "covered"; detail = { k: "noInk", p: {} }; noInkRect = rect;
          }
        } else if (st) {
          const c = hiContrast(rgb, st.bg);
          const bgHex = "#" + st.bg.map((v) => Math.round(v).toString(16).padStart(2, "0")).join("");
          const noInk = st.inkFrac < HI_RULES.coveredInkFrac && st.areaPx >= HI_RULES.minCoveredAreaPx;
          if (noInk) noInkRect = rect;
          if (noInk && c < HI_RULES.faintContrast) {
            type = "same-color"; detail = { k: "contrast", p: { fg: run.color, bg: bgHex, ratio: c.toFixed(2) } };
          } else if (noInk) {
            type = "covered"; detail = { k: "covered", p: { fg: run.color } };
          } else if (c < HI_RULES.faintContrast) {
            type = "faint"; detail = { k: "contrast", p: { fg: run.color, bg: bgHex, ratio: c.toFixed(2) } };
          }
        }
      }
      if (type && noInkRect) noInkChecks.push({ index: pageFindings.length, rect: noInkRect });
      if (type) pageFindings.push({ type, detail, bigTilted: run.bigTilted, text: run.text, bbox: run.bbox.slice(), parts: [{ text: run.text, bbox: run.bbox.slice(), baseY: run.base[1], size: run.effSize }] });
      else visibleRuns.push(run);
    }

    // Text that leaves no ink: is it covered, or are its letters empty? Draw the
    // text alone, on white and on black, so text of any colour shows.
    if (noInkChecks.length) {
      const skip = new Set(Object.entries(OPS)
        .filter(([n]) => /^(constructPath|rawFillPath|fill|eoFill|stroke|fillStroke|eoFillStroke|closeStroke|closeFillStroke|closeEOFillStroke|shadingFill|clip|eoClip)$|^paint.*(Image|Mask)/.test(n))
        .map(([, v]) => v));
      const textAlone = async (bg) => {
        ctx.fillStyle = bg;
        ctx.fillRect(0, 0, canvas.width, canvas.height);
        await page.render({ canvas, canvasContext: ctx, viewport, annotationMode: DISABLE, background: bg,
          operationsFilter: (i, list) => !(list && skip.has(list.fnArray[i])) }).promise;
        return ctx.getImageData(0, 0, canvas.width, canvas.height);
      };
      const onWhite = await textAlone("#ffffff"), onBlack = await textAlone("#000000");
      ctx.putImageData(img, 0, 0);
      for (const c of noInkChecks) {
        if (hiInkShare(onWhite, c.rect, [255, 255, 255]) + hiInkShare(onBlack, c.rect, [0, 0, 0]) > 0.002) continue;
        const f = pageFindings[c.index];
        const marks = hiMarkShare(imgNoText, c.rect);
        f.type = "blank-font";
        f.detail = { k: marks >= HI_RULES.drawnLabelMarks[0] && marks <= HI_RULES.drawnLabelMarks[1] ? "blankFontDrawn" : "blankFont", p: {} };
      }
    }

    // Merge consecutive runs hidden the same way, but only when they sit close
    // together (same line, or the next line). Far-apart pieces stay separate findings.
    const merged = [];
    for (const f of pageFindings) {
      const last = merged[merged.length - 1];
      const prev = last && last.parts[last.parts.length - 1];
      const near = prev && (() => {
        const h = Math.max(prev.bbox[3] - prev.bbox[1], f.bbox[3] - f.bbox[1], 1);
        const vGap = Math.max(0, Math.max(prev.bbox[1], f.bbox[1]) - Math.min(prev.bbox[3], f.bbox[3]));
        const hGap = Math.max(0, Math.max(prev.bbox[0], f.bbox[0]) - Math.min(prev.bbox[2], f.bbox[2]));
        const sizeRatio = Math.max(prev.size, f.parts[0].size) / Math.max(1e-3, Math.min(prev.size, f.parts[0].size));
        return vGap < h * 1.2 && hGap < h * 6 && sizeRatio < 1.6;
      })();
      if (last && last.type === f.type && (near || f.type === "ocr-layer")) {
        const sameLine = Math.abs(prev.baseY - f.parts[0].baseY) < 0.5 * Math.max(prev.size, 1);
        const gap = f.bbox[0] - prev.bbox[2];
        const space = !sameLine || (gap > 0.2 * prev.size && !/\s$/.test(last.text) && !/^\s/.test(f.text));
        last.text += (space ? " " : "") + f.text;
        last.bbox = [Math.min(last.bbox[0], f.bbox[0]), Math.min(last.bbox[1], f.bbox[1]), Math.max(last.bbox[2], f.bbox[2]), Math.max(last.bbox[3], f.bbox[3])];
        last.parts.push(...f.parts);
        last.bigTilted = last.bigTilted && f.bigTilted;
        if (last.detail && last.detail.k === "blankFontDrawn" && !(f.detail && f.detail.k === "blankFontDrawn")) last.detail = { k: "blankFont", p: {} };
      } else merged.push({ ...f, parts: f.parts.slice() });
    }
    for (const f of merged) {
      f.text = f.text.replace(/\s+/g, " ").trim();
      if ((f.text.match(/\p{L}/gu) || []).length < HI_RULES.minLetters) continue;
      f.patterns = hiMatchPatterns(f.text);
      const meaningful = f.text.replace(/[\s\W_]/gu, "").length;
      if (f.patterns.length) f.severity = "high";
      else if (f.type === "ocr-layer") f.severity = "low";
      else if (f.detail && f.detail.k === "blankFontDrawn") f.severity = "low";
      else if ((f.type === "faint" || f.type === "same-color") && f.bigTilted &&
               f.text.split(/\s+/).filter((w) => /\p{L}/u.test(w)).length <= HI_RULES.watermarkWords) {
        f.severity = "low";
        f.detail = { k: "watermark", p: f.detail && f.detail.p ? f.detail.p : {} };
      }
      // Faint text: below 1.25:1 contrast it is practically invisible to a reader.
      else if (f.type === "faint") f.severity = meaningful >= 3 && parseFloat(f.detail && f.detail.p && f.detail.p.ratio) < HI_RULES.nearInvisibleContrast ? "medium" : "low";
      else f.severity = meaningful >= 3 ? "medium" : "low";
      f.page = p;
      f.rectPx = toPx(f.bbox).map((v) => v / scale);
      // Group parts into visual lines for the "UV light" preview.
      const lines = [];
      for (const part of f.parts) {
        const ln = lines.find((l) => Math.abs(l.baseY - part.baseY) < 0.5 * Math.max(l.size, 1));
        if (ln) {
          ln.text += (part.bbox[0] - ln.bbox[2] > 0.2 * ln.size && !/\s$/.test(ln.text) ? " " : "") + part.text;
          ln.bbox = [Math.min(ln.bbox[0], part.bbox[0]), Math.min(ln.bbox[1], part.bbox[1]), Math.max(ln.bbox[2], part.bbox[2]), Math.max(ln.bbox[3], part.bbox[3])];
        } else lines.push({ text: part.text, bbox: part.bbox.slice(), baseY: part.baseY, size: part.size });
      }
      f.lines = lines.map((l) => ({ text: l.text.replace(/\s+/g, " ").trim(), rectPx: toPx(l.bbox).map((v) => v / scale) }));
      delete f.parts;
      delete f.bigTilted;
      report.findings.push(f);
    }

    // Unicode tricks anywhere in the page's text (visible or not)
    uni.scan(runs.map((r) => r.text).join(" "), null, p);

    // clean text: only what a human can see, roughly in reading order
    let lines = [], cur = "", lastY = null, lastX = null;
    for (const r of visibleRuns) {
      const yy = r.base[1];
      if (lastY !== null && Math.abs(yy - lastY) > r.effSize * 0.5) { lines.push(cur); cur = ""; lastX = null; }
      else if (lastX !== null && r.bbox[0] - lastX > r.effSize * 0.15 && cur && !/\s$/.test(cur)) cur += " ";
      cur += r.text;
      lastY = yy; lastX = r.bbox[2];
    }
    if (cur) lines.push(cur);
    const pageClean = lines.join("\n").replace(HI_INVISIBLE_ALL, "");
    report.cleanTextPages.push(pageClean);
    // Instructions in plain sight are not hidden, but they are worth a look: a
    // font can be built to show different letters than the text it stores.
    const visPats = hiMatchPatterns(pageClean);
    if (visPats.length) {
      report.findings.push({ type: "visible-instruction", severity: "low", page: p, patterns: visPats,
        text: hiClip(visPats.map((m) => {
          const i = hiNormalize(pageClean).indexOf(m);
          return i < 0 ? m : hiNormalize(pageClean).slice(Math.max(0, i - 60), i + m.length + 60).replace(/\s+/g, " ").trim();
        }).join("\n")), detail: { k: "visibleInstr", p: {} } });
    }

    const previewPromise = hiPreview(canvas, previewMaxW); // encodes in the background
    report.pages.push({
      num: p, previewPromise, cssWidth: viewport.width / scale, cssHeight: viewport.height / scale,
      looksScanned, runCount: runs.length,
      ms: { parse: Math.round(tB - tA), render: Math.round(tC - tB), check: Math.round(performance.now() - tC) },
    });
    page.cleanup();
  }

  // document info + annotations
  try {
    const md = await doc.getMetadata();
    const info = md && md.info ? md.info : {};
    const fields = ["Title", "Subject", "Keywords", "Author", "Creator", "Producer"];
    for (const k of fields) {
      const v = typeof info[k] === "string" ? info[k] : "";
      if (!v) continue;
      const pats = hiMatchPatterns(v);
      if (pats.length) report.findings.push({ type: "metadata", severity: "high", text: v, detail: { k: "field", p: { f: k } }, patterns: pats, page: null });
      uni.scan(v, { k: "field", p: { f: k } }, null);
    }
    const xmp = md && md.metadata ? md.metadata.getAll() : {};
    for (const [k, v] of Object.entries(xmp || {})) {
      const s = Array.isArray(v) ? v.join(" ") : String(v);
      const pats = hiMatchPatterns(s);
      if (pats.length && !report.findings.some((f) => f.type === "metadata" && f.text === s))
        report.findings.push({ type: "metadata", severity: "high", text: s, detail: { k: "field", p: { f: "XMP " + k } }, patterns: pats, page: null });
    }
    // Non-standard info keys (/HiddenMarker, a program's banner key, ...). Nothing shows
    // these on screen, so any readable text in them is reported.
    const custom = info.Custom instanceof Map ? [...info.Custom] : Object.entries(info.Custom || {});
    for (const [k, raw] of custom) {
      const v = typeof raw === "string" ? raw : raw && typeof raw.name === "string" ? raw.name : "";
      if (!v) continue;
      uni.scan(v, { k: "field", p: { f: k } }, null);
      if (!hiReadable(v)) continue;
      const pats = hiMatchPatterns(v);
      const known = hiKnownCustomKey(k);
      report.findings.push({
        type: "metadata-custom", text: hiClip(v), patterns: pats, page: null,
        severity: pats.length ? "high" : known || hiMachineValue(v) ? "low" : "medium",
        detail: { k: known ? "customKnown" : hiMachineValue(v) ? "customMachine" : "field", p: { f: k } },
      });
    }
  } catch (_) { /* no metadata */ }

  // Annotations, including the ones flagged hidden (pdf.js leaves those out
  // unless asked for every intent).
  const attachments = [];   // { id, name, description, page }
  for (let p = 1; p <= doc.numPages; p++) {
    try {
      const page = await doc.getPage(p);
      const annots = await page.getAnnotations({ intent: "any" });
      for (const an of annots) {
        const sub = an.subtype || "?";
        if (an.fileId && an.file) {
          attachments.push({ id: an.fileId, name: an.file.filename || an.fileId, description: an.file.description || "", page: p });
        }
        const fv = Array.isArray(an.fieldValue) ? an.fieldValue.join(" ") : an.fieldValue;
        const body = [an.contentsObj && an.contentsObj.str, typeof fv === "string" ? fv : ""].filter(Boolean).join("\n");
        const s = [an.contentsObj && an.contentsObj.str, an.titleObj && an.titleObj.str, fv].filter((v) => typeof v === "string" && v).join(" ");
        if (!s) continue;
        uni.scan(s, { k: "annot", p: { t: sub } }, p);
        const flags = an.annotationFlags || 0;
        // A popup only displays its parent's text; the parent is checked itself.
        const hidden = sub !== "Popup" && (flags & (HI_AF.INVISIBLE | HI_AF.HIDDEN | HI_AF.NOVIEW)) !== 0;
        if (hidden && hiReadable(body)) {
          const pats = hiMatchPatterns(s);
          const flagNames = Object.entries(HI_AF).filter(([, bit]) => flags & bit).map(([n]) => n).join(", ");
          const f = { type: "hidden-annotation", severity: pats.length ? "high" : "medium", text: hiClip(body), patterns: pats, page: p,
            detail: { k: "annotHidden", p: { t: sub, flags: flagNames } } };
          if (Array.isArray(an.rect) && an.rect.length === 4) {
            const vt = page.getViewport({ scale: 1 }).transform;
            const a = hiApply([an.rect[0], an.rect[1]], vt), b = hiApply([an.rect[2], an.rect[3]], vt);
            f.bbox = an.rect.slice();
            f.rectPx = [Math.min(a[0], b[0]), Math.min(a[1], b[1]), Math.max(a[0], b[0]), Math.max(a[1], b[1])];
          }
          report.findings.push(f);
          continue;
        }
        const pats = hiMatchPatterns(s);
        if (pats.length) report.findings.push({ type: "annotation", severity: "high", text: s, detail: { k: "annot", p: { t: sub } }, patterns: pats, page: p });
      }
    } catch (_) { /* ignore */ }
  }

  // Embedded files (document-level, plus those attached through a note).
  try {
    const list = await doc.getAttachments();
    const entries = list instanceof Map ? [...list] : Object.entries(list || {});
    for (const [id, spec] of entries) {
      attachments.unshift({ id, name: (spec && spec.filename) || id, description: (spec && spec.description) || "", page: null });
    }
  } catch (_) { /* none */ }
  const seenAttach = new Set();
  for (const at of attachments) {
    if (seenAttach.has(at.id)) continue;
    seenAttach.add(at.id);
    let bytes = null;
    try { bytes = await doc.getAttachmentContent(at.id); } catch (_) { bytes = null; }
    // A PDF inside the PDF: scan it the same way, a couple of levels deep.
    if (bytes && /%PDF-/.test(new TextDecoder("latin1").decode(bytes.subarray(0, 1024))) && depth < HI_RULES.maxNestedDepth) {
      let child = null;
      try { child = await hiAnalyze(pdfjsLib, bytes.slice(), { ...opts, depth: depth + 1, onProgress: () => {} }); } catch (_) { child = null; }
      if (child) {
        for (const pg of child.pages) if (pg.previewBlobUrl) URL.revokeObjectURL(pg.previewBlobUrl);
        report.findings.push({ type: "attachment", severity: "low", text: at.name, patterns: [], page: at.page,
          detail: { k: "attachmentPdf", p: { f: at.name, size: bytes.length.toLocaleString("en-US"), n: child.findings.length } } });
        for (const cf of child.findings) {
          const { id, rectPx, lines, ...rest } = cf;
          report.findings.push({ ...rest, page: at.page, inFile: cf.inFile ? at.name + " › " + cf.inFile : at.name, inPage: cf.inPage || cf.page || null });
        }
        continue;
      }
    }
    const content = hiDecodeAttachment(bytes);
    const desc = hiReadable(at.description) ? at.description : "";
    const textual = content !== null && hiReadable(content);
    const full = [desc, textual ? content : ""].filter(Boolean).join("\n\n");
    const where = { k: "attachment", p: { f: at.name } };
    if (full) uni.scan(full, where, at.page);
    const pats = full ? hiMatchPatterns(full.slice(0, 200000)) : [];
    const size = bytes ? bytes.length.toLocaleString("en-US") : "0";
    report.findings.push({
      type: "attachment", text: full ? hiClip(full) : at.name, patterns: pats, page: at.page,
      severity: pats.length ? "high" : full && !hiStandardInvoiceXml(content) ? "medium" : "low",
      detail: { k: textual ? "attachment" : "attachmentBin", p: { f: at.name, size } },
    });
  }

  // Bookmarks
  for (const title of await hiOutlineTitles(doc)) {
    uni.scan(title, { k: "outline", p: {} }, null);
    const pats = hiMatchPatterns(title);
    if (pats.length) report.findings.push({ type: "outline", severity: "high", text: hiClip(title), patterns: pats, page: null, detail: { k: "outline", p: {} } });
  }

  for (const u of uni.finish()) { if (u.patterns.length) u.severity = "high"; report.findings.push(u); }

  // Raw safety net, last: anything it finds is not explained by the checks above.
  if (opts.rawScan !== false) {
    const hay = report.cleanTextPages.join("\n") + "\n" + report.findings.map((f) => f.text + " " + (f.patterns || []).join(" ")).join("\n");
    try { for (const h of await hiRawScan(rawBytes, hay)) report.findings.push(h); } catch (_) { /* best effort */ }
  }
  const sevRank = { high: 0, medium: 1, low: 2 };
  // Within a severity: findings stored on no page first (they are shown above the
  // pages), then page by page, so numbers read 1, 2, 3 ... down the preview.
  const pageKey = (f) => (f.page ? f.page : 0);
  report.findings.sort((a, b) => sevRank[a.severity] - sevRank[b.severity] || pageKey(a) - pageKey(b));
  report.findings.forEach((f, i) => { f.id = i + 1; });
  const has = (s) => report.findings.some((f) => f.severity === s);
  report.verdict = has("high") ? "danger" : has("medium") ? "suspicious" : "clean";
  Object.defineProperty(report, "sourceBytes", { value: rawBytes, enumerable: false });
  report.cleanText = report.cleanTextPages.map((t, i) => (report.numPages > 1 ? `--- ${i + 1} ---\n` : "") + t).join("\n\n");
  canvas.width = canvas.height = 0;
  for (const pg of report.pages) {
    const pv = await pg.previewPromise;
    pg.previewUrl = pv.url;
    pg.previewBlob = pv.blob;
    pg.previewBlobUrl = pv.url.startsWith("blob:") ? pv.url : null;
    delete pg.previewPromise;
  }
  try { await task.destroy(); } catch (_) { /* already closed */ }
  return report;
}

// ---------------------------------------------------------------------------
// 6. Cleaned copy: every page as a person sees it, nothing else.
// Each page is drawn the way a viewer shows it (visible notes and form fields
// included, hidden ones not) and stored as a picture in a new, minimal PDF.
// Hidden text, metadata, attachments, hidden notes, bookmarks and scripts are
// not carried over. The trade-off: text in the copy can't be selected.
// ---------------------------------------------------------------------------
async function hiCleanPdf(pdfjsLib, data, opts = {}) {
  const onProgress = opts.onProgress || (() => {});
  const quality = opts.quality || 0.85;
  const task = pdfjsLib.getDocument({
    data: data.slice(), isEvalSupported: false, useSystemFonts: true, verbosity: 0,
    stopAtErrors: false, enableXfa: false,
  });
  const doc = await task.promise;
  const ENABLE = pdfjsLib.AnnotationMode ? pdfjsLib.AnnotationMode.ENABLE : 1;
  const canvas = document.createElement("canvas");
  const ctx = canvas.getContext("2d");
  const enc = new TextEncoder();
  const parts = [], offsets = [];
  let pos = 0;
  const push = (x) => { const b = typeof x === "string" ? enc.encode(x) : x; parts.push(b); pos += b.length; };
  const obj = (num, ...body) => { offsets[num] = pos; push(`${num} 0 obj\n`); body.forEach(push); push("\nendobj\n"); };
  push(new Uint8Array([0x25, 0x50, 0x44, 0x46, 0x2D, 0x31, 0x2E, 0x34, 0x0A, 0x25, 0xE2, 0xE3, 0xCF, 0xD3, 0x0A])); // %PDF-1.4 + binary marker
  const n = doc.numPages, kids = [];
  try {
    for (let p = 1; p <= n; p++) {
      onProgress(p, n);
      const page = await doc.getPage(p);
      const v1 = page.getViewport({ scale: 1 });
      // About 144 dpi, capped so very large pages stay within canvas limits.
      const scale = Math.min(2, Math.sqrt(8e6 / Math.max(1, v1.width * v1.height)));
      const vp = page.getViewport({ scale });
      canvas.width = Math.max(1, Math.ceil(vp.width));
      canvas.height = Math.max(1, Math.ceil(vp.height));
      ctx.fillStyle = "#ffffff";
      ctx.fillRect(0, 0, canvas.width, canvas.height);
      await page.render({ canvas, canvasContext: ctx, viewport: vp, annotationMode: ENABLE }).promise;
      const blob = await new Promise((res) => canvas.toBlob(res, "image/jpeg", quality));
      if (!blob) throw new Error("page " + p + " could not be encoded");
      const jpg = new Uint8Array(await blob.arrayBuffer());
      const pageNo = 3 + (p - 1) * 3, contNo = pageNo + 1, imgNo = pageNo + 2;
      const W = v1.width.toFixed(2), H = v1.height.toFixed(2);
      obj(imgNo, `<< /Type /XObject /Subtype /Image /Width ${canvas.width} /Height ${canvas.height} ` +
        `/ColorSpace /DeviceRGB /BitsPerComponent 8 /Filter /DCTDecode /Length ${jpg.length} >>\nstream\n`, jpg, "\nendstream");
      const cs = `q ${W} 0 0 ${H} 0 0 cm /Im0 Do Q`;
      obj(contNo, `<< /Length ${cs.length} >>\nstream\n${cs}\nendstream`);
      obj(pageNo, `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${W} ${H}] ` +
        `/Resources << /XObject << /Im0 ${imgNo} 0 R >> >> /Contents ${contNo} 0 R >>`);
      kids.push(pageNo);
      page.cleanup();
    }
  } finally {
    canvas.width = canvas.height = 0;
    try { await task.destroy(); } catch (_) { /* already closed */ }
  }
  obj(1, "<< /Type /Catalog /Pages 2 0 R >>");
  obj(2, `<< /Type /Pages /Kids [${kids.map((k) => k + " 0 R").join(" ")}] /Count ${n} >>`);
  const infoNo = 3 + n * 3;
  obj(infoNo, "<< /Producer (UnderInk cleaned copy) >>");
  const xref = pos;
  push(`xref\n0 ${infoNo + 1}\n0000000000 65535 f \n`);
  for (let i = 1; i <= infoNo; i++) push(String(offsets[i]).padStart(10, "0") + " 00000 n \n");
  push(`trailer\n<< /Size ${infoNo + 1} /Root 1 0 R /Info ${infoNo} 0 R >>\nstartxref\n${xref}\n%%EOF\n`);
  return new Blob(parts, { type: "application/pdf" });
}
