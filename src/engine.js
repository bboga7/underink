// UnderInk detection engine.
// Runs entirely in the browser. No network, no AI: every check is a plain rule.
//
// How it works, per page:
//   1. Walk pdf.js's operator list and re-trace every text-drawing command,
//      tracking position, size, colour, opacity, render mode and hidden layers.
//   2. Render the page to a canvas and look at the pixels under each piece of
//      text: does the ink actually show up, and does it contrast with what is
//      behind it?
//   3. Flag text a human cannot see but a text extractor (or an AI) will read.
//
// This file is concatenated with app.js at build time (no module exports).

const HI_RULES = {
  tinyFontPt: 2,          // effective size below this is unreadable
  squeezeScale: 0.1,      // horizontal scaling below 10% is unreadable
  minAlpha: 0.1,          // fill opacity below this is invisible
    faintContrast: 1.5,     // below this: very faint (low severity)
  nearInvisibleContrast: 1.25, // below this, faint text is practically invisible (medium)
  coveredInkFrac: 0.004,  // fewer ink pixels than this: covered by something
  drawnLabelMarks: [0.04, 0.7], // text in a font that draws nothing, over marks covering this share of its box: an exported label
  watermarkPt: 36,        // faint text at least this big...
  watermarkFlatPt: 72,    // ...and tilted, or at least this big when level...
  watermarkWords: 3,      // ...with this many words or fewer: a watermark such as DRAFT
  minCoveredAreaPx: 40,
  minLetters: 3,          // hidden fragments with fewer letters (symbols, rules) are ignored
  renderScale: 2,
  partialOffShare: 0.25,  // a line with at least this share of its box beyond the page edge
  maxNestedDepth: 2,      // PDFs inside PDFs are scanned this deep
};

// Share of a box that lies outside the page box.
function hiOutsideShare(bb, view) {
  const w = Math.max(1e-6, bb[2] - bb[0]), h = Math.max(1e-6, bb[3] - bb[1]);
  const iw = Math.max(0, Math.min(bb[2], view[2]) - Math.max(bb[0], view[0]));
  const ih = Math.max(0, Math.min(bb[3], view[3]) - Math.max(bb[1], view[1]));
  return 1 - (iw * ih) / (w * h);
}

// Non-standard document-info keys. Any readable text in them is reported. Two
// kinds stay low risk, so ordinary files don't raise alarms:
//  - generic property names that office and typesetting programs fill in on
//    their own (company, comments, language, ...), and
//  - values that look machine-written rather than like prose (see hiMachineValue).
// No product or vendor names are listed: the rules look at the value's shape.
const HI_KNOWN_CUSTOM_EXACT = new Set(["company", "sourcemodified", "comments", "manager", "category",
  "contenttypeid", "language", "lang", "doi", "robots", "isbn", "copyright", "license", "licence",
  "pdfversion", "version", "marked", "trapped", "source", "url"]);
const HI_GUID = /[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/i;
function hiKnownCustomKey(key) {
  const k = String(key);
  // A key that embeds a GUID was generated by a program (e.g. document labels).
  return HI_KNOWN_CUSTOM_EXACT.has(k.toLowerCase()) || HI_GUID.test(k);
}
// Values that are identifiers or program banners rather than prose: dates, URLs,
// domains, GUIDs, hashes, booleans, numbers, version strings, mostly-digit IDs,
// file paths and PDF conformance levels ("PDF/X-4", "PDF/A-2b").
function hiMachineValue(s) {
  const v = s.trim();
  if (/^D:\d{4}/.test(v) || /^\d{4}-\d{2}-\d{2}/.test(v)) return true;                       // dates
  if (/^(https?:\/\/|www\.|doi:|urn:|10\.\d{4,}\/)\S*$/i.test(v)) return true;                // URLs, DOIs
  if (/^[a-z0-9-]+(\.[a-z0-9-]+)+$/i.test(v) && /[a-z]/i.test(v)) return true;               // bare domains
  if (/^[{(]?[0-9a-f]{8}(-[0-9a-f]{4}){3}-[0-9a-f]{12}[)}]?$/i.test(v) || /^[0-9a-f]{16,}$/i.test(v) ||
      /^uuid:[0-9a-f-]+$/i.test(v)) return true;                                              // GUIDs, hashes
  if (/^(true|false|yes|no|on|off|none|null)$/i.test(v) || /^[\d\s.,:/+-]+$/.test(v)) return true; // booleans, numbers
  if (/\bv(ersion)?\.?\s*\d+(\.\d+)+/i.test(v) || /\b\d+\.\d+\.\d+/.test(v)) return true;    // version banners
  if (/^PDF\/[A-Z]{1,3}-?\d[a-z]?(:\d{4})?$/i.test(v)) return true;                           // PDF/X-4, PDF/A-2b
  if (!/\s/.test(v) && v.length >= 6 && (v.match(/\d/g) || []).length / v.length >= 0.4) return true; // IDs
  if (!/\s/.test(v) && /[\\/]/.test(v) && /\.[a-z0-9]{2,4}$/i.test(v)) return true;          // file paths
  return false;
}
// Embedded files that standards put there on purpose: structured e-invoice XML,
// recognised by its content (standard root element or namespace), not by name.
function hiStandardInvoiceXml(text) {
  const head = String(text || "").slice(0, 4000);
  return /^\s*(<\?xml[^>]*>\s*)?</.test(head) &&
    /<([\w-]+:)?CrossIndustryInvoice\b|urn:cen\.eu:en16931|urn:oasis:names:specification:ubl:schema:xsd:Invoice/i.test(head);
}

// Annotation flags, as defined by the PDF standard.
const HI_AF = { INVISIBLE: 1, HIDDEN: 2, NOVIEW: 32 };
const HI_ATTACH_MAX_SCAN = 1 << 20;   // decode at most 1 MB of an attachment
const HI_SHOW_MAX = 4000;             // characters of hidden text shown in a finding

// Does this string contain text a person (or an AI) would read?
function hiReadable(s) {
  return typeof s === "string" && (s.replace(HI_INVISIBLE_ALL, "").match(/\p{L}/gu) || []).length >= HI_RULES.minLetters;
}
function hiClip(s) {
  const t = s.replace(/\r\n?/g, "\n").replace(/[ \t]+\n/g, "\n").replace(/\n{3,}/g, "\n\n").trim();
  return t.length > HI_SHOW_MAX ? t.slice(0, HI_SHOW_MAX) + " …" : t;
}

// Turn an attachment's bytes into text, or null if it is a binary file.
function hiDecodeAttachment(bytes) {
  if (!bytes || !bytes.length) return null;
  const b = bytes.subarray(0, HI_ATTACH_MAX_SCAN);
  let text = null;
  try {
    if (b[0] === 0xFF && b[1] === 0xFE) text = new TextDecoder("utf-16le").decode(b.subarray(2));
    else if (b[0] === 0xFE && b[1] === 0xFF) text = new TextDecoder("utf-16be").decode(b.subarray(2));
    else {
      try { text = new TextDecoder("utf-8", { fatal: true }).decode(b); } catch (_) {
        if (b.subarray(0, 8192).includes(0)) return null;
        text = new TextDecoder("windows-1252").decode(b);
      }
    }
  } catch (_) { return null; }
  if (text.charCodeAt(0) === 0xFEFF) text = text.slice(1);
  const sample = text.slice(0, 20000);
  const ctrl = (sample.match(/[\u0000-\u0008\u000E-\u001F\u007F\uFFFD]/g) || []).length;
  return ctrl / Math.max(1, sample.length) > 0.02 ? null : text;
}

