// Look-alike letters (Cyrillic, Greek) mapped to the Latin letter they imitate.
const HI_CONFUSABLES = {
  "а": "a", "е": "e", "о": "o", "р": "p", "с": "c", "у": "y", "х": "x",
  "і": "i", "ј": "j", "ѕ": "s", "ԁ": "d", "ӏ": "l", "к": "k", "м": "m",
  "н": "h", "т": "t", "в": "b", "А": "A", "В": "B", "Е": "E", "К": "K",
  "М": "M", "Н": "H", "О": "O", "Р": "P", "С": "C", "Т": "T", "Х": "X",
  "І": "I", "Ј": "J", "Ѕ": "S", "ο": "o", "α": "a", "ε": "e", "ι": "i",
  "κ": "k", "ν": "v", "ρ": "p", "τ": "t", "υ": "u", "χ": "x", "Ο": "O",
  "Α": "A", "Β": "B", "Ε": "E", "Η": "H", "Ι": "I", "Κ": "K", "Μ": "M",
  "Ν": "N", "Ρ": "P", "Τ": "T", "Χ": "X", "İ": "I",
};
const HI_CONFUSABLE_RE = new RegExp("[" + Object.keys(HI_CONFUSABLES).join("") + "]", "g");

// Undo common tricks that break a phrase apart so a regex can't see it:
// invisible characters, soft hyphens, full-width or styled letters, look-alikes.
function hiNormalize(text) {
  let t = String(text).replace(HI_INVISIBLE_ALL, "").replace(/\u00AD/g, "");
  try { t = t.normalize("NFKC"); } catch (_) { /* old engine */ }
  // Only swap look-alikes inside words that are mostly Latin, so real Greek or
  // Cyrillic text is left alone.
  return t.replace(/[\p{L}]+/gu, (w) => {
    if (!HI_CONFUSABLE_RE.test(w)) return w;
    HI_CONFUSABLE_RE.lastIndex = 0;
    const latin = (w.match(/[A-Za-z]/g) || []).length;
    return latin * 2 >= w.length - latin ? w.replace(HI_CONFUSABLE_RE, (c) => HI_CONFUSABLES[c]) : w;
  });
}

// "I g n o r e  a l l  p r e v i o u s": letters split by single spaces.
const HI_SPACED = /(?:(?<!\p{L})\p{L} ){5,}\p{L}(?!\p{L})/gu;
// The same patterns with every space optional, tried only on de-spaced text.
const HI_PATTERNS_LOOSE = HI_PATTERNS.map((re) => new RegExp(
  re.source.replace(/\\b/g, "").replace(/\\s\*|\\s\+|\\s| /g, "\\s*"), re.flags.includes("u") ? re.flags : re.flags + "u"));

function hiMatchPatterns(text) {
  if (!text) return [];
  const hits = [];
  const add = (m) => { const v = m.replace(/\s+/g, " ").trim(); if (v && !hits.includes(v)) hits.push(v); };
  const norm = hiNormalize(text);
  for (const re of HI_PATTERNS) { const m = norm.match(re); if (m) add(m[0]); }
  if (!hits.length) {
    const spaced = norm.match(HI_SPACED);
    if (spaced && spaced.join("").length >= 20) {
      const squeezed = spaced.map((s) => s.replace(/ /g, "")).join(" ");
      for (const re of HI_PATTERNS_LOOSE) { const m = squeezed.match(re); if (m) add(m[0]); }
    }
  }
  // Base64-wrapped instructions ("aWdub3JlIGFsbCBwcmV2aW91cy...").
  if (!hits.length && typeof atob === "function") {
    for (const b64 of (norm.match(/[A-Za-z0-9+/]{24,}={0,2}/g) || []).slice(0, 20)) {
      let dec = "";
      try { dec = atob(b64.length % 4 ? b64 + "=".repeat(4 - (b64.length % 4)) : b64); } catch (_) { continue; }
      if (!/^[\x20-\x7E\s]+$/.test(dec)) continue;
      for (const re of HI_PATTERNS) { const m = dec.match(re); if (m) add("base64: " + m[0]); }
    }
  }
  return hits;
}


// ---- small matrix helpers (pdf.js convention: [a b c d e f]) ----
const HI_ID = [1, 0, 0, 1, 0, 0];
function hiMul(m1, m2) { // apply m2 first, then m1
  return [
    m1[0] * m2[0] + m1[2] * m2[1],
    m1[1] * m2[0] + m1[3] * m2[1],
    m1[0] * m2[2] + m1[2] * m2[3],
    m1[1] * m2[2] + m1[3] * m2[3],
    m1[0] * m2[4] + m1[2] * m2[5] + m1[4],
    m1[1] * m2[4] + m1[3] * m2[5] + m1[5],
  ];
}
function hiApply(p, m) { return [p[0] * m[0] + p[1] * m[2] + m[4], p[0] * m[1] + p[1] * m[3] + m[5]]; }
function hiArr6(a) { return a ? [a[0], a[1], a[2], a[3], a[4], a[5]] : HI_ID.slice(); }

function hiHexToRgb(hex) {
  if (typeof hex !== "string" || hex[0] !== "#" || hex.length < 7) return null;
  return [parseInt(hex.slice(1, 3), 16), parseInt(hex.slice(3, 5), 16), parseInt(hex.slice(5, 7), 16)];
}
function hiLum([r, g, b]) {
  const f = (v) => { v /= 255; return v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4); };
  return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b);
}
function hiContrast(a, b) {
  const la = hiLum(a), lb = hiLum(b);
  return (Math.max(la, lb) + 0.05) / (Math.min(la, lb) + 0.05);
}
function hiDist(a, b) { return Math.hypot(a[0] - b[0], a[1] - b[1], a[2] - b[2]); }

// ---------------------------------------------------------------------------
// 1. Trace text runs from the operator list.
// ---------------------------------------------------------------------------
function hiTraceRuns(OPS, opList, page, ocConfig) {
  const runs = [];
  const images = [];
  const ocStack = [];          // true = this marked-content level is hidden
  const stack = [];
  let gs = {
    ctm: HI_ID.slice(), fill: "#000000", stroke: "#000000", fillAlpha: 1, strokeAlpha: 1,
    font: null, fontSize: 0, charSpacing: 0, wordSpacing: 0, hscale: 1, rise: 0,
    leading: 0, renderMode: 0,
  };
  let tm = HI_ID.slice(), x = 0, y = 0, lineX = 0, lineY = 0;
  const fontCache = new Map();

  const fontMatrixOf = (name) => {
    if (fontCache.has(name)) return fontCache.get(name);
    let fm = [0.001, 0, 0, 0.001, 0, 0], vertical = false;
    try {
      if (page.commonObjs.has(name)) {
        const f = page.commonObjs.get(name);
        if (f && f.fontMatrix) fm = Array.from(f.fontMatrix);
        if (f && f.vertical) vertical = true;
      }
    } catch (_) { /* fall back to default */ }
    const v = { fm, vertical };
    fontCache.set(name, v);
    return v;
  };

  const moveText = (dx, dy) => { lineX += dx; lineY += dy; x = lineX; y = lineY; };
  const hiddenByOC = () => ocStack.some(Boolean);

  const showText = (glyphs) => {
    const size = gs.fontSize;
    const dir = size < 0 ? -1 : 1;
    const absSize = Math.abs(size);
    const { fm, vertical } = gs.font ? fontMatrixOf(gs.font) : { fm: [0.001, 0, 0, 0.001, 0, 0], vertical: false };
    const widthScale = absSize * fm[0];
    let adv = 0, text = "", lastWasSpace = true;
    for (const g of glyphs) {
      if (typeof g === "number") {
        adv += -g * absSize / 1000;
        if (g < -180 && !lastWasSpace) { text += " "; lastWasSpace = true; }
        continue;
      }
      if (!g) continue;
      const spacing = (g.isSpace ? gs.wordSpacing : 0) + gs.charSpacing;
      adv += (g.width || 0) * widthScale + spacing * dir;
      const u = g.unicode || "";
      text += u;
      lastWasSpace = /\s$/.test(u);
    }
    const hscale = gs.hscale;
    const startX = x, startY = y + gs.rise;
    if (vertical) y -= adv; else x += adv * hscale;

    const full = hiMul(gs.ctm, tm);
    // run box in text space: from baseline-descent to ascent
    const x0 = startX, x1 = startX + (vertical ? absSize : adv * hscale);
    const yB = startY - 0.22 * absSize, yT = startY + 0.8 * absSize;
    const pts = [[x0, yB], [x1, yB], [x0, yT], [x1, yT]].map((p) => hiApply(p, full));
    const xs = pts.map((p) => p[0]), ys = pts.map((p) => p[1]);
    const det = Math.abs(full[0] * full[3] - full[1] * full[2]);
    const effSize = absSize * Math.sqrt(det);
    const base = hiApply([startX, startY], full);
    const tilt = Math.abs(((Math.atan2(full[1], full[0]) * 180 / Math.PI) % 90 + 90) % 90);
    const useStroke = gs.renderMode === 1 || gs.renderMode === 5;
    runs.push({
      text,
      bbox: [Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)],
      base,
      effSize,
      hscale: Math.abs(hscale),
      color: useStroke ? gs.stroke : gs.fill,
      alpha: useStroke ? gs.strokeAlpha : gs.fillAlpha,
      renderMode: gs.renderMode,
      ocHidden: hiddenByOC(),
      bigTilted: effSize >= HI_RULES.watermarkPt && ((tilt > 10 && tilt < 80) || effSize >= HI_RULES.watermarkFlatPt),
    });
  };

  const { fnArray, argsArray } = opList;
  for (let i = 0; i < fnArray.length; i++) {
    const fn = fnArray[i], a = argsArray[i];
    switch (fn) {
      case OPS.save: stack.push({ ...gs, ctm: gs.ctm.slice() }); break;
      case OPS.restore: if (stack.length) gs = stack.pop(); break;
      case OPS.transform: gs.ctm = hiMul(gs.ctm, hiArr6(a)); break;
      case OPS.paintFormXObjectBegin:
        stack.push({ ...gs, ctm: gs.ctm.slice() });
        if (a && a[0]) gs.ctm = hiMul(gs.ctm, hiArr6(a[0]));
        break;
      case OPS.paintFormXObjectEnd: if (stack.length) gs = stack.pop(); break;
      case OPS.setFillRGBColor: gs.fill = a[0]; break;
      case OPS.setStrokeRGBColor: gs.stroke = a[0]; break;
      case OPS.setFillColorN: case OPS.setFillColor: case OPS.setFillColorSpace:
        if (!(a && typeof a[0] === "string" && a[0][0] === "#")) gs.fill = null; break;
      case OPS.setGState:
        for (const [k, v] of a[0] || []) {
          if (k === "ca") gs.fillAlpha = v;
          else if (k === "CA") gs.strokeAlpha = v;
          else if (k === "Font" && Array.isArray(v)) { gs.font = v[0]; gs.fontSize = v[1]; }
        }
        break;
      case OPS.beginText: tm = HI_ID.slice(); x = y = lineX = lineY = 0; break;
      case OPS.setTextMatrix: tm = hiArr6(a.length === 1 ? a[0] : a); x = y = lineX = lineY = 0; break;
      case OPS.setFont: gs.font = a[0]; gs.fontSize = a[1]; break;
      case OPS.setCharSpacing: gs.charSpacing = a[0]; break;
      case OPS.setWordSpacing: gs.wordSpacing = a[0]; break;
      case OPS.setHScale: gs.hscale = a[0] / 100; break;
      case OPS.setTextRise: gs.rise = a[0]; break;
      case OPS.setLeading: gs.leading = -a[0]; break;
      case OPS.setTextRenderingMode: gs.renderMode = a[0]; break;
      case OPS.moveText: moveText(a[0], a[1]); break;
      case OPS.setLeadingMoveText: gs.leading = a[1]; moveText(a[0], a[1]); break;
      case OPS.nextLine: moveText(0, gs.leading); break;
      case OPS.showText: case OPS.showSpacedText: showText(a[0]); break;
      case OPS.nextLineShowText: moveText(0, gs.leading); showText(a[0]); break;
      case OPS.nextLineSetSpacingShowText:
        gs.wordSpacing = a[0]; gs.charSpacing = a[1]; moveText(0, gs.leading); showText(a[2]); break;
      case OPS.beginMarkedContent: ocStack.push(false); break;
      case OPS.beginMarkedContentProps: {
        let hidden = false;
        if (a[0] === "OC" && a[1] && ocConfig) {
          try { hidden = !ocConfig.isVisible(a[1]); } catch (_) { hidden = false; }
        }
        ocStack.push(hidden);
        break;
      }
      case OPS.endMarkedContent: ocStack.pop(); break;
      case OPS.paintImageXObject: case OPS.paintInlineImageXObject:
      case OPS.paintImageMaskXObject: case OPS.paintImageXObjectRepeat: {
        const pts = [[0, 0], [1, 0], [0, 1], [1, 1]].map((p) => hiApply(p, gs.ctm));
        const xs = pts.map((p) => p[0]), ys = pts.map((p) => p[1]);
        images.push([Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)]);
        break;
      }
      default: break;
    }
  }
  return { runs, images };
}

// Some generators (design tools, browsers) place every glyph separately. Join runs that
// share a style and sit next to each other on one line, so visibility is judged
// per word or line instead of per letter.
function hiGroupRuns(runs) {
  const out = [];
  for (const r of runs) {
    const last = out[out.length - 1];
    const sameStyle = last && last.color === r.color && last.alpha === r.alpha && last.renderMode === r.renderMode &&
      last.ocHidden === r.ocHidden && Math.abs(last.effSize - r.effSize) <= 0.2 * Math.max(last.effSize, r.effSize, 0.01) &&
      Math.abs(last.hscale - r.hscale) < 0.05;
    const sz = last ? Math.max(last.effSize, 0.5) : 1;
    const sameLine = last && Math.abs(last.lastBaseY - r.base[1]) < 0.3 * sz;
    const gap = last ? r.bbox[0] - last.bbox[2] : 0;
    if (sameStyle && sameLine && gap > -0.5 * sz && gap < 1.5 * sz) {
      const space = gap > 0.2 * sz && !/\s$/.test(last.text) && !/^\s/.test(r.text);
      last.text += (space ? " " : "") + r.text;
      last.bbox = [Math.min(last.bbox[0], r.bbox[0]), Math.min(last.bbox[1], r.bbox[1]), Math.max(last.bbox[2], r.bbox[2]), Math.max(last.bbox[3], r.bbox[3])];
      last.lastBaseY = r.base[1];
    } else {
      out.push({ ...r, bbox: r.bbox.slice(), lastBaseY: r.base[1] });
    }
  }
  return out;
}

